"""Abstraction in front of memory persistence. Method names mirror the
concrete SQLiteMemoryStore (companion/skills/memory_notes.py) so the port
documents a real adapter rather than an idealized, different-shaped API --
the storage engine becomes swappable later without touching call sites.
"""
from typing import List, Optional, Protocol, Tuple


class MemoryStore(Protocol):
    def remember_note(self, text: str, user_id=None, due_date: Optional[str] = None) -> None: ...

    def recall_notes(self, question: str, user_id=None) -> str: ...

    def due_notes_for(self, user_id, date_str: str) -> List[Tuple[int, str]]: ...

    def clear_due(self, item_id) -> None: ...

    def append_turn(self, user_id, role: str, content: str) -> None: ...

    def recent_context(self, user_id, turns: int = 3) -> List[Tuple[str, str]]: ...

    def item_count(self, user_id) -> int: ...

    def compact_user_memory(self, user_id, keep_recent: Optional[int] = None) -> bool: ...

    def remember_episode(self, user_id, summary_text: str) -> Optional[int]: ...
